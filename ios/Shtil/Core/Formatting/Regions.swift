/// Субъекты РФ для профиля. Код — номер региона (как в кодах автомобильных номеров и в `region_code` сервера).
/// `aliases` — основы слов (столица, крупные города) для поиска и разбора текста «о себе»: слово подходит, если начинается с основы
/// и длиннее её не больше чем на два знака («казан» → «Казани», «Казанью»).
enum Region {
    struct Item: Hashable, Identifiable, Sendable {
        let code: String
        let title: String
        let aliases: [String]
        var id: String { code }
    }

    private static func r(_ code: String, _ title: String, _ aliases: String...) -> Item {
        Item(code: code, title: title, aliases: aliases)
    }

    /// Сначала крупнейшие, дальше по алфавиту названий.
    static let all: [Item] = {
        let top = ["77", "78", "50", "47", "23", "16", "66", "54", "52", "63"]
        let byCode = Dictionary(uniqueKeysWithValues: items.map { ($0.code, $0) })
        let rest = items.filter { !top.contains($0.code) }.sorted { $0.title < $1.title }
        return top.compactMap { byCode[$0] } + rest
    }()

    static func title(for code: String?) -> String? {
        code.flatMap { c in all.first { $0.code == c }?.title }
    }

    /// Ищет регион по названию или городу в свободном тексте (текст уже в нижнем регистре, «ё» → «е»).
    /// Побеждает регион, названный раньше всех; «Нижний Новгород» разбирается отдельно, чтобы не спутать с Великим Новгородом.
    static func find(in text: String) -> Item? {
        if text.range(of: "нижн\\S* новгород", options: .regularExpression) != nil { return item(code: "52") }
        let words = text.split(whereSeparator: { !$0.isLetter && $0 != "-" }).map(String.init)
        var best: (index: Int, item: Item)?
        for item in all {
            for alias in item.aliases {
                if alias.contains(" ") {
                    if let range = text.range(of: alias) {
                        let index = text.distance(from: text.startIndex, to: range.lowerBound)
                        if best == nil || index < best!.index { best = (index, item) }
                    }
                    continue
                }
                if let i = words.firstIndex(where: { matches($0, stem: alias) }) {
                    // позиция слова в символах текста, чтобы сравнивать с многословными совпадениями
                    let index = words[..<i].reduce(0) { $0 + $1.count + 1 }
                    if best == nil || index < best!.index { best = (index, item) }
                }
            }
        }
        return best?.item
    }

    static func item(code: String) -> Item? { all.first { $0.code == code } }

    /// Поиск в списке: по началу любого слова названия или по алиасу.
    static func search(_ query: String) -> [Item] {
        let q = query.lowercased().replacingOccurrences(of: "ё", with: "е").trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return all }
        return all.filter { item in
            let title = item.title.lowercased().replacingOccurrences(of: "ё", with: "е")
            return title.split(separator: " ").contains { $0.hasPrefix(q) } || title.hasPrefix(q)
                || item.aliases.contains { $0.hasPrefix(q) || q.hasPrefix($0) }
        }
    }

    /// Слово подходит, если это основа плюс падежное окончание («казан» + «и»); произвольное продолжение («казанова») не подходит.
    private static let endings: Set<String> = [
        "", "а", "е", "у", "ы", "и", "ю", "я", "ь", "ой", "ей", "ом", "ем", "ью", "ая", "ую", "ий", "ый", "ого", "ском",
        "ская", "ской", "скую", "ский", "ского", "ские", "ских", "цы", "цев", "ец",
    ]

    private static func matches(_ word: String, stem: String) -> Bool {
        guard word.hasPrefix(stem) else { return false }
        return endings.contains(String(word.dropFirst(stem.count)))
    }

