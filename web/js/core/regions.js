const TOP = ['77', '78', '50', '47', '23', '16', '66', '54', '52', '63'];
const byCode = new Map(ITEMS.map((i) => [i.code, i]));

/** Сначала крупнейшие, дальше по алфавиту названий. */
export const REGIONS = [
  ...TOP.map((c) => byCode.get(c)),
  ...ITEMS.filter((i) => !TOP.includes(i.code)).sort((a, b) => a.title.localeCompare(b.title, 'ru')),
];

const ENDINGS = new Set([
  '', 'а', 'е', 'у', 'ы', 'и', 'ю', 'я', 'ь', 'ой', 'ей', 'ом', 'ем', 'ью', 'ая', 'ую', 'ий', 'ый', 'ого', 'ском',
  'ская', 'ской', 'скую', 'ский', 'ского', 'ские', 'ских', 'цы', 'цев', 'ец',
]);

const norm = (s) => s.toLowerCase().replaceAll('ё', 'е');

export function regionTitle(code) {
  return code ? byCode.get(code)?.title ?? null : null;
}

/** Слово подходит, если это основа плюс падежное окончание («казан» + «и»); «казанова» не подходит. */
function matchesStem(word, stem) {
  return word.startsWith(stem) && ENDINGS.has(word.slice(stem.length));
}

/** Ищет регион по названию или городу в тексте (нижний регистр, «ё» → «е»); побеждает названный раньше всех. */
export function findRegion(text) {
  if (/нижн\S* новгород/.test(text)) return byCode.get('52');
  const words = text.split(/[^\p{L}-]+/u).filter(Boolean);
  let best = null;
  for (const item of REGIONS) {
    for (const alias of item.aliases) {
      let index = -1;
      if (alias.includes(' ')) {
        index = text.indexOf(alias);
      } else {
        const i = words.findIndex((w) => matchesStem(w, alias));
        if (i >= 0) index = words.slice(0, i).reduce((n, w) => n + w.length + 1, 0);
      }
      if (index >= 0 && (best === null || index < best.index)) best = { index, item };
    }
  }
  return best ? best.item : null;
}

/** Поиск в списке: по началу слова названия или по алиасу. */
export function searchRegions(query) {
  const q = norm(query).trim();
  if (!q) return REGIONS;
  return REGIONS.filter((item) => {
    const title = norm(item.title);
    return title.split(' ').some((w) => w.startsWith(q)) || title.startsWith(q) || item.aliases.some((a) => a.startsWith(q) || q.startsWith(a));
  });
}
